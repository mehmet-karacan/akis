CREATE FUNCTION katalog_alt_model_dongusunu_engelle() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.ust_alt_model_id IS NOT NULL AND EXISTS (
        WITH RECURSIVE ustler(id) AS (
            SELECT NEW.ust_alt_model_id UNION ALL
            SELECT a.ust_alt_model_id FROM akis.alt_model a JOIN ustler u ON u.id = a.id
             WHERE a.ust_alt_model_id IS NOT NULL AND a.proje_id = NEW.proje_id
        ) SELECT 1 FROM ustler WHERE id = NEW.id
    ) THEN RAISE EXCEPTION 'Alt model ağacı döngü içeremez.' USING ERRCODE = '23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_alt_model_dongu BEFORE INSERT OR UPDATE OF ust_alt_model_id, proje_id ON alt_model
FOR EACH ROW EXECUTE FUNCTION katalog_alt_model_dongusunu_engelle();

CREATE FUNCTION katalog_iliski_dogrula() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE goruntu_nesne_id BIGINT; goruntu_surum_id BIGINT; test_sonucu VARCHAR(20);
BEGIN
    IF TG_TABLE_NAME = 'tanim_veri_nesnesi' THEN
        SELECT veri_nesnesi_id INTO STRICT goruntu_nesne_id FROM akis.sema_goruntusu WHERE id = NEW.sema_goruntusu_id;
        IF goruntu_nesne_id <> NEW.veri_nesnesi_id THEN
            RAISE EXCEPTION 'Şema görüntüsü seçilen veri nesnesine ait değildir.' USING ERRCODE = '23514';
        END IF;
    ELSE
        SELECT baglanti_surumu_id INTO STRICT goruntu_surum_id FROM akis.sema_goruntusu WHERE id = NEW.sema_goruntusu_id;
        SELECT sonuc INTO STRICT test_sonucu FROM akis.baglanti_testi
         WHERE baglanti_surumu_id = NEW.baglanti_surumu_id AND uuid = NEW.basarili_baglanti_testi_uuid;
        IF goruntu_surum_id <> NEW.baglanti_surumu_id OR test_sonucu <> 'BASARILI' THEN
            RAISE EXCEPTION 'Oracle kanıtı başarılı test ve görüntü sürümüyle eşleşmelidir.' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_tanim_veri_nesnesi_dogrula BEFORE INSERT OR UPDATE ON tanim_veri_nesnesi
FOR EACH ROW EXECUTE FUNCTION katalog_iliski_dogrula();
CREATE TRIGGER trg_oracle_kaniti_dogrula BEFORE INSERT OR UPDATE ON sema_goruntusu_oracle_kaniti
FOR EACH ROW EXECUTE FUNCTION katalog_iliski_dogrula();

CREATE FUNCTION degismez_katalog_kanitini_koru() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Katalog kanıtı değiştirilemez.' USING ERRCODE = '55000'; END $$;
CREATE TRIGGER trg_sema_goruntusu_degismez BEFORE UPDATE OR DELETE ON sema_goruntusu
FOR EACH ROW EXECUTE FUNCTION degismez_katalog_kanitini_koru();
CREATE TRIGGER trg_kolon_goruntusu_degismez BEFORE UPDATE OR DELETE ON kolon_goruntusu
