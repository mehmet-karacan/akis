CREATE TABLE model (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proje_id BIGINT NOT NULL REFERENCES proje(id),
    mantiksal_sema_id BIGINT NOT NULL,
    kod VARCHAR(100) NOT NULL,
    ad VARCHAR(200) NOT NULL,
    aciklama VARCHAR(2000),
    arsivlenme_zamani TIMESTAMPTZ,
    uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    olusturan_kullanici_id BIGINT REFERENCES kullanici(id),
    guncellenme_zamani TIMESTAMPTZ,
    guncelleyen_kullanici_id BIGINT REFERENCES kullanici(id),
    versiyon_no BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT pk_model PRIMARY KEY (id),
    CONSTRAINT uq_model_uuid UNIQUE (uuid),
    CONSTRAINT uq_model_proje_kod UNIQUE (proje_id, kod),
    CONSTRAINT uq_model_proje_id UNIQUE (proje_id, id),
    CONSTRAINT fk_model_mantiksal_sema FOREIGN KEY (proje_id, mantiksal_sema_id)
        REFERENCES mantiksal_sema(proje_id, id),
    CONSTRAINT ck_model_kod CHECK (kod ~ '^[A-Z][A-Z0-9_]{0,99}$'),
    CONSTRAINT ck_model_audit CHECK (versiyon_no > 0 AND
        (guncellenme_zamani IS NULL OR guncellenme_zamani >= olusturulma_zamani))
);

