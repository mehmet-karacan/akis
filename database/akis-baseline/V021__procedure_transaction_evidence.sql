-- Statement execution and transaction durability are deliberately separate facts.
ALTER TABLE prosedur_adim_durumu
    ADD COLUMN transaction_outcome VARCHAR(30) NOT NULL DEFAULT 'NOT_ATTEMPTED',
    ADD COLUMN durable_commit_reference VARCHAR(200),
    ADD CONSTRAINT ck_prosedur_adim_transaction_outcome CHECK(transaction_outcome IN
      ('NOT_ATTEMPTED','EXECUTED_UNCOMMITTED','COMMIT_CONFIRMED','ROLLBACK_CONFIRMED','OUTCOME_UNKNOWN')),
    ADD CONSTRAINT ck_prosedur_adim_commit_reference CHECK(
      (transaction_outcome='COMMIT_CONFIRMED' AND durable_commit_reference IS NOT NULL)
      OR (transaction_outcome<>'COMMIT_CONFIRMED' AND durable_commit_reference IS NULL));

CREATE TABLE islem_grubu_kaniti (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
 proje_id BIGINT NOT NULL,
 is_talebi_id BIGINT NOT NULL,
 calistirma_id BIGINT NOT NULL,
 grup_kodu VARCHAR(100) NOT NULL,
 baglanti_surumu_uuid UUID NOT NULL,
 kanal INTEGER NOT NULL CHECK(kanal BETWEEN 0 AND 9),
 uye_adim_kodlari JSONB NOT NULL CHECK(jsonb_typeof(uye_adim_kodlari)='array'),
 izolasyon VARCHAR(30) NOT NULL,
 commit_siniri VARCHAR(30) NOT NULL CHECK(commit_siniri IN('PER_STATEMENT','END_OF_GROUP')),
 operasyon_anahtari_ozeti CHAR(64) NOT NULL CHECK(operasyon_anahtari_ozeti ~ '^[0-9a-f]{64}$'),
 runtime_plan_ozeti CHAR(64) NOT NULL CHECK(runtime_plan_ozeti ~ '^[0-9a-f]{64}$'),
 olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 olusturan_kullanici_id BIGINT REFERENCES kullanici(id),
 FOREIGN KEY(proje_id,is_talebi_id) REFERENCES is_talebi(proje_id,id),
 FOREIGN KEY(proje_id,calistirma_id) REFERENCES calistirma(proje_id,id),
 UNIQUE(proje_id,id),
 UNIQUE(calistirma_id,grup_kodu),
 UNIQUE(is_talebi_id,operasyon_anahtari_ozeti)
);

CREATE TABLE islem_grubu_durumu (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
 proje_id BIGINT NOT NULL,
 islem_grubu_kaniti_id BIGINT NOT NULL,
 outcome VARCHAR(30) NOT NULL DEFAULT 'NOT_ATTEMPTED' CHECK(outcome IN
   ('NOT_ATTEMPTED','EXECUTED_UNCOMMITTED','COMMIT_CONFIRMED','ROLLBACK_CONFIRMED','OUTCOME_UNKNOWN')),
 dispatch_zamani TIMESTAMPTZ,
 sonuc_zamani TIMESTAMPTZ,
 durable_commit_reference VARCHAR(200),
 hata_kodu VARCHAR(100),
 versiyon_no BIGINT NOT NULL DEFAULT 1 CHECK(versiyon_no>0),
 guncellenme_zamani TIMESTAMPTZ,
 FOREIGN KEY(proje_id,islem_grubu_kaniti_id) REFERENCES islem_grubu_kaniti(proje_id,id),
 UNIQUE(islem_grubu_kaniti_id),
 CHECK((outcome='COMMIT_CONFIRMED' AND durable_commit_reference IS NOT NULL)
       OR (outcome<>'COMMIT_CONFIRMED' AND durable_commit_reference IS NULL))
);
CREATE TRIGGER trg_islem_grubu_kaniti_degismez
