 UNIQUE(is_talebi_id,adim_kodu)
);

CREATE TABLE yukleme_bolumu (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
 proje_id BIGINT NOT NULL,
 veri_yukleme_plani_id BIGINT NOT NULL,
 bolum_kodu VARCHAR(80) NOT NULL,
 alt_sinir JSONB,
 ust_sinir JSONB,
 durum VARCHAR(20) NOT NULL DEFAULT 'PLANNED' CHECK(durum IN
   ('PLANNED','ACTIVE','COMPLETE','FAILED','BLOCKED')),
 olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(proje_id,veri_yukleme_plani_id) REFERENCES veri_yukleme_plani(proje_id,id),
 UNIQUE(proje_id,id),
 UNIQUE(veri_yukleme_plani_id,bolum_kodu),
 CHECK((alt_sinir IS NULL OR jsonb_typeof(alt_sinir)='object')
       AND (ust_sinir IS NULL OR jsonb_typeof(ust_sinir)='object'))
);

CREATE TABLE yukleme_parcasi (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
 proje_id BIGINT NOT NULL,
 yukleme_bolumu_id BIGINT NOT NULL,
 workspace_uuid UUID NOT NULL,
 sira_no BIGINT NOT NULL CHECK(sira_no>0),
 work_unit_key CHAR(64) NOT NULL CHECK(work_unit_key ~ '^[0-9a-f]{64}$'),
 runtime_plan_ozeti CHAR(64) NOT NULL CHECK(runtime_plan_ozeti ~ '^[0-9a-f]{64}$'),
 girdi_ozeti CHAR(64) NOT NULL CHECK(girdi_ozeti ~ '^[0-9a-f]{64}$'),
 alt_sinir JSONB,
 ust_sinir JSONB,
 son_anahtar JSONB,
 payload_ozeti CHAR(64) NOT NULL CHECK(payload_ozeti ~ '^[0-9a-f]{64}$'),
 girdi_satir_sayisi BIGINT NOT NULL CHECK(girdi_satir_sayisi>=0),
 girdi_bayt_sayisi BIGINT NOT NULL CHECK(girdi_bayt_sayisi>=0),
 hedef_defter_referansi VARCHAR(200),
 son_hata_kodu VARCHAR(100),
 durum VARCHAR(30) NOT NULL DEFAULT 'INTENT_RECORDED' CHECK(durum IN
   ('INTENT_RECORDED','DISPATCHED','COMMIT_CONFIRMED','ROLLBACK_CONFIRMED','OUTCOME_UNKNOWN','BLOCKED')),
 kontrol_noktasi_id BIGINT REFERENCES kontrol_noktasi(id),
 olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(proje_id,yukleme_bolumu_id) REFERENCES yukleme_bolumu(proje_id,id),
 UNIQUE(proje_id,id),
 UNIQUE(yukleme_bolumu_id,sira_no),
 UNIQUE(work_unit_key),
 CHECK((alt_sinir IS NULL OR jsonb_typeof(alt_sinir)='object')
       AND (ust_sinir IS NULL OR jsonb_typeof(ust_sinir)='object')
       AND (son_anahtar IS NULL OR jsonb_typeof(son_anahtar)='object')),
 CHECK((durum='COMMIT_CONFIRMED' AND hedef_defter_referansi IS NOT NULL AND son_hata_kodu IS NULL)
       OR (durum IN('ROLLBACK_CONFIRMED','OUTCOME_UNKNOWN','BLOCKED') AND son_hata_kodu IS NOT NULL AND hedef_defter_referansi IS NULL)
       OR (durum IN('INTENT_RECORDED','DISPATCHED') AND hedef_defter_referansi IS NULL AND son_hata_kodu IS NULL))
);

