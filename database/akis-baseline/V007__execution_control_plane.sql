CREATE TABLE is_talebi (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY, proje_id BIGINT NOT NULL REFERENCES proje(id),
 yayin_id BIGINT NOT NULL, istek_ozeti CHAR(64) NOT NULL, is_turu VARCHAR(20) NOT NULL DEFAULT 'CALISTIR',
 oncelik INTEGER NOT NULL DEFAULT 50, planlanan_zaman TIMESTAMPTZ,
 parametre_sema_surumu INTEGER NOT NULL DEFAULT 1, parametre JSONB NOT NULL DEFAULT '{}'::jsonb,
 uuid UUID NOT NULL DEFAULT gen_random_uuid(), olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 olusturan_kullanici_id BIGINT REFERENCES kullanici(id), guncellenme_zamani TIMESTAMPTZ,
 guncelleyen_kullanici_id BIGINT REFERENCES kullanici(id), versiyon_no BIGINT NOT NULL DEFAULT 1,
 CONSTRAINT pk_is_talebi PRIMARY KEY(id), CONSTRAINT uq_is_talebi_uuid UNIQUE(uuid),
 CONSTRAINT uq_is_talebi_proje_id UNIQUE(proje_id,id),
 CONSTRAINT fk_is_talebi_yayin FOREIGN KEY(proje_id,yayin_id) REFERENCES yayin(proje_id,id),
 CONSTRAINT ck_is_talebi_ozet CHECK(istek_ozeti ~ '^[0-9a-f]{64}$'),
 CONSTRAINT ck_is_talebi_tur CHECK(is_turu IN('CALISTIR','TEST','KESIF','ONIZLEME')),
 CONSTRAINT ck_is_talebi_oncelik CHECK(oncelik BETWEEN 0 AND 100),
 CONSTRAINT ck_is_talebi_parametre CHECK(parametre_sema_surumu>0 AND jsonb_typeof(parametre)='object'),
 CONSTRAINT ck_is_talebi_audit CHECK(versiyon_no>0 AND (guncellenme_zamani IS NULL OR guncellenme_zamani>=olusturulma_zamani))
);

CREATE TABLE calistirma (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY, proje_id BIGINT NOT NULL REFERENCES proje(id),
 is_talebi_id BIGINT NOT NULL, deneme_no INTEGER NOT NULL, yayin_ozeti CHAR(64) NOT NULL,
 plan_ozeti CHAR(64) NOT NULL, baslatma_turu VARCHAR(20) NOT NULL,
 onceki_calistirma_id BIGINT,
 uuid UUID NOT NULL DEFAULT gen_random_uuid(), olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 olusturan_kullanici_id BIGINT REFERENCES kullanici(id), guncellenme_zamani TIMESTAMPTZ,
 guncelleyen_kullanici_id BIGINT REFERENCES kullanici(id), versiyon_no BIGINT NOT NULL DEFAULT 1,
 CONSTRAINT pk_calistirma PRIMARY KEY(id), CONSTRAINT uq_calistirma_uuid UNIQUE(uuid),
 CONSTRAINT uq_calistirma_deneme UNIQUE(is_talebi_id,deneme_no), CONSTRAINT uq_calistirma_proje_id UNIQUE(proje_id,id),
 CONSTRAINT fk_calistirma_talep FOREIGN KEY(proje_id,is_talebi_id) REFERENCES is_talebi(proje_id,id),
 CONSTRAINT fk_calistirma_onceki FOREIGN KEY(proje_id,onceki_calistirma_id) REFERENCES calistirma(proje_id,id),
 CONSTRAINT ck_calistirma_deneme CHECK(deneme_no>0),
 CONSTRAINT ck_calistirma_ozet CHECK(yayin_ozeti ~ '^[0-9a-f]{64}$' AND plan_ozeti ~ '^[0-9a-f]{64}$'),
 CONSTRAINT ck_calistirma_baslatma CHECK(baslatma_turu IN('ILK','YENIDEN_DENE','DEVAM_ET')),
 CONSTRAINT ck_calistirma_onceki CHECK((baslatma_turu='ILK' AND onceki_calistirma_id IS NULL) OR (baslatma_turu<>'ILK' AND onceki_calistirma_id IS NOT NULL)),
 CONSTRAINT ck_calistirma_audit CHECK(versiyon_no>0 AND (guncellenme_zamani IS NULL OR guncellenme_zamani>=olusturulma_zamani))
);

CREATE TABLE calistirma_durumu (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY, proje_id BIGINT NOT NULL REFERENCES proje(id), calistirma_id BIGINT NOT NULL,
