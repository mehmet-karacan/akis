 CONSTRAINT ck_prosedur_adim_durumu_audit CHECK(versiyon_no>0 AND (guncellenme_zamani IS NULL OR guncellenme_zamani>=olusturulma_zamani))
);

CREATE FUNCTION degismez_calistirma_kanitini_koru() RETURNS TRIGGER LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Çalıştırma kanıtı değiştirilemez.' USING ERRCODE='55000'; END $$;
CREATE TRIGGER trg_calistirma_olayi_degismez BEFORE UPDATE OR DELETE ON calistirma_olayi FOR EACH ROW EXECUTE FUNCTION degismez_calistirma_kanitini_koru();
CREATE TRIGGER trg_prosedur_adim_kaniti_degismez BEFORE UPDATE OR DELETE ON prosedur_adim_kaniti FOR EACH ROW EXECUTE FUNCTION degismez_calistirma_kanitini_koru();

CREATE INDEX ix_calistirma_proje ON calistirma(proje_id,olusturulma_zamani DESC);
CREATE INDEX ix_calistirma_olayi_run ON calistirma_olayi(proje_id,calistirma_id,olay_no);
CREATE INDEX ix_calistirma_adimi_agac ON calistirma_adimi(proje_id,calistirma_id,ust_adim_id,sira_no);
