 kiralama_bitis_zamani TIMESTAMPTZ, yasam_sinyali_zamani TIMESTAMPTZ,
 baslama_zamani TIMESTAMPTZ, bitis_zamani TIMESTAMPTZ, iptal_isteme_zamani TIMESTAMPTZ,
 uuid UUID NOT NULL DEFAULT gen_random_uuid(), olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 olusturan_kullanici_id BIGINT REFERENCES kullanici(id), guncellenme_zamani TIMESTAMPTZ,
 guncelleyen_kullanici_id BIGINT REFERENCES kullanici(id), versiyon_no BIGINT NOT NULL DEFAULT 1,
 CONSTRAINT pk_calistirma_durumu PRIMARY KEY(id), CONSTRAINT uq_calistirma_durumu_uuid UNIQUE(uuid),
 CONSTRAINT uq_calistirma_durumu_calistirma UNIQUE(calistirma_id), CONSTRAINT uq_calistirma_durumu_proje_id UNIQUE(proje_id,id),
 CONSTRAINT fk_calistirma_durumu_calistirma FOREIGN KEY(proje_id,calistirma_id) REFERENCES calistirma(proje_id,id),
 CONSTRAINT ck_calistirma_durumu CHECK(durum IN('BEKLIYOR','SAHIPLENILDI','CALISIYOR','IPTAL_ISTENDI','BASARILI','BASARISIZ','IPTAL','SONUCU_BILINMIYOR')),
 CONSTRAINT ck_calistirma_durumu_sayac CHECK(nesil_no>=0 AND son_olay_no>=0),
 CONSTRAINT ck_calistirma_durumu_zaman CHECK(bitis_zamani IS NULL OR baslama_zamani IS NULL OR bitis_zamani>=baslama_zamani),
 CONSTRAINT ck_calistirma_durumu_audit CHECK(versiyon_no>0 AND (guncellenme_zamani IS NULL OR guncellenme_zamani>=olusturulma_zamani))
);

