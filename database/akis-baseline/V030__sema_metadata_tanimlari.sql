-- Sistem genelinde (proje bağımsız) veritabanı yapı metadatasını tutan tanım katmanı.
-- Şema -> tablo -> kolon -> kısıt -> ilişki -> indeks -> sequence hiyerarşisini temsil eder.
-- Bu tablolar kendi kendini de belgeler: kendi şema/tablo/kolon kayıtları
-- akis.tablo_tanimlari / akis.kolon_tanimlari içine eklenir.
--
-- Standart kolon sırası (bu dosyadaki ve sonraki tüm *_tanimlari tabloları için):
--   1) id
--   2) üst tabloya FK (varsa)
--   3) sira_no (üst içinde sıralama gerekiyorsa)
--   4) ad
--   5) aciklama
--   6) tabloya özgü diğer iş alanları
--   7) audit bloğu (hep bu sırayla): uuid, olusturulma_zamani, olusturan_kullanici_id,
--      guncellenme_zamani, guncelleyen_kullanici_id

CREATE TABLE akis.sema_tanimlari (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ad VARCHAR(200) NOT NULL,
    aciklama VARCHAR(2000),
    uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    olusturan_kullanici_id BIGINT REFERENCES akis.kullanici(id),
    guncellenme_zamani TIMESTAMPTZ,
    guncelleyen_kullanici_id BIGINT REFERENCES akis.kullanici(id),
    CONSTRAINT pk_sema_tanimlari PRIMARY KEY (id),
    CONSTRAINT uq_sema_tanimlari_uuid UNIQUE (uuid),
    CONSTRAINT uq_sema_tanimlari_ad UNIQUE (ad),
    CONSTRAINT ck_sema_tanimlari_ad CHECK (ad ~ '^[a-z][a-z0-9_]{0,99}$'),
    CONSTRAINT ck_sema_tanimlari_audit CHECK (
        guncellenme_zamani IS NULL OR guncellenme_zamani >= olusturulma_zamani
    )
);

COMMENT ON TABLE akis.sema_tanimlari IS 'Sistemdeki veritabanı şemalarının (namespace) metadata tanımı.';
COMMENT ON COLUMN akis.sema_tanimlari.id IS 'Yüzeysel (surrogate) birincil anahtar.';
COMMENT ON COLUMN akis.sema_tanimlari.ad IS 'Veritabanındaki gerçek şema adı (ayrı bir kod/etiket tutulmaz).';
COMMENT ON COLUMN akis.sema_tanimlari.aciklama IS 'Şemanın iş amacı/kapsamı.';
COMMENT ON COLUMN akis.sema_tanimlari.uuid IS 'Dış sistemlere/API''ye açılan kararlı benzersiz kimlik.';
COMMENT ON COLUMN akis.sema_tanimlari.olusturulma_zamani IS 'Kaydın oluşturulma zamanı.';
COMMENT ON COLUMN akis.sema_tanimlari.olusturan_kullanici_id IS 'Kaydı oluşturan kullanıcı.';
COMMENT ON COLUMN akis.sema_tanimlari.guncellenme_zamani IS 'Kaydın son güncellenme zamanı (yoksa hiç güncellenmemiştir).';
COMMENT ON COLUMN akis.sema_tanimlari.guncelleyen_kullanici_id IS 'Kaydı son güncelleyen kullanıcı.';

