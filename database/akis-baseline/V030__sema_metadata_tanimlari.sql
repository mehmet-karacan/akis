    sahibi_kolon_tanimi_id BIGINT REFERENCES akis.kolon_tanimlari(id),
    uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    olusturan_kullanici_id BIGINT REFERENCES akis.kullanici(id),
    guncellenme_zamani TIMESTAMPTZ,
    guncelleyen_kullanici_id BIGINT REFERENCES akis.kullanici(id),
    CONSTRAINT pk_sira_tanimlari PRIMARY KEY (id),
    CONSTRAINT uq_sira_tanimlari_uuid UNIQUE (uuid),
    CONSTRAINT uq_sira_tanimlari_sema_ad UNIQUE (sema_tanimi_id, ad),
    CONSTRAINT ck_sira_tanimlari_ad CHECK (ad ~ '^[a-z][a-z0-9_]{0,99}$'),
    CONSTRAINT ck_sira_tanimlari_artis_miktari CHECK (artis_miktari <> 0),
    CONSTRAINT ck_sira_tanimlari_araliq CHECK (
        min_deger IS NULL OR max_deger IS NULL OR min_deger <= max_deger
    ),
    CONSTRAINT ck_sira_tanimlari_audit CHECK (
        guncellenme_zamani IS NULL OR guncellenme_zamani >= olusturulma_zamani
    )
);

