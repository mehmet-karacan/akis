    proje_id, baglanti_id, baglanti_surumu_id, durum_kodu)
SELECT proje_id, baglanti_id, id, 'DRAFT'
  FROM baglanti_surumu;

CREATE OR REPLACE FUNCTION fn_baglanti_surumu_yasam_dongusu_olustur()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO entegrasyon.baglanti_surumu_yasam_dongusu(
        proje_id, baglanti_id, baglanti_surumu_id, durum_kodu)
    VALUES (NEW.proje_id, NEW.baglanti_id, NEW.id, 'DRAFT');
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_baglanti_surumu_yasam_dongusu_olustur
AFTER INSERT ON baglanti_surumu
FOR EACH ROW EXECUTE FUNCTION fn_baglanti_surumu_yasam_dongusu_olustur();

