CREATE OR REPLACE FUNCTION fn_baglanti_surumu_yasam_dongusu_dogrula()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_surum_baglanti_id BIGINT;
    v_test entegrasyon.baglanti_surumu_testi%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Connection version lifecycle rows cannot be deleted.';
    END IF;

    SELECT baglanti_id
      INTO v_surum_baglanti_id
      FROM entegrasyon.baglanti_surumu
     WHERE proje_id = NEW.proje_id
       AND id = NEW.baglanti_surumu_id;
    IF v_surum_baglanti_id IS NULL OR v_surum_baglanti_id <> NEW.baglanti_id THEN
        RAISE EXCEPTION 'Connection version lifecycle relationship is invalid.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.durum_kodu <> 'DRAFT'
                OR NEW.durum_surumu <> 1
                OR NEW.hedef_kimlik_surumu IS NOT NULL
                OR NEW.hedef_parmak_izi IS NOT NULL
                OR NEW.son_basarili_test_uuid IS NOT NULL
                OR NEW.test_edilme_zamani IS NOT NULL
                OR NEW.aktiflestirilme_zamani IS NOT NULL THEN
            RAISE EXCEPTION 'Connection version lifecycle must start in DRAFT.';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.proje_id <> OLD.proje_id
            OR NEW.baglanti_id <> OLD.baglanti_id
            OR NEW.baglanti_surumu_id <> OLD.baglanti_surumu_id THEN
        RAISE EXCEPTION 'Connection version lifecycle identity is immutable.';
    END IF;
    IF NEW.durum_surumu <> OLD.durum_surumu + 1 THEN
        RAISE EXCEPTION 'Connection version lifecycle state version is stale.';
    END IF;
    IF OLD.hedef_parmak_izi IS NOT NULL
            AND (NEW.hedef_parmak_izi IS DISTINCT FROM OLD.hedef_parmak_izi
                 OR NEW.hedef_kimlik_surumu IS DISTINCT FROM OLD.hedef_kimlik_surumu) THEN
        RAISE EXCEPTION 'Pinned Oracle target identity is immutable.';
    END IF;

    IF NOT ((OLD.durum_kodu = 'DRAFT' AND NEW.durum_kodu = 'TESTED')
            OR (OLD.durum_kodu = 'TESTED' AND NEW.durum_kodu = 'TESTED')
            OR (OLD.durum_kodu = 'TESTED' AND NEW.durum_kodu = 'ACTIVE')
            OR (OLD.durum_kodu = 'ACTIVE' AND NEW.durum_kodu = 'ACTIVE')) THEN
        RAISE EXCEPTION 'Invalid connection version lifecycle transition.';
    END IF;

    IF OLD.durum_kodu = 'TESTED' AND NEW.durum_kodu = 'ACTIVE' THEN
        IF NEW.hedef_kimlik_surumu IS DISTINCT FROM OLD.hedef_kimlik_surumu
                OR NEW.hedef_parmak_izi IS DISTINCT FROM OLD.hedef_parmak_izi
                OR NEW.son_basarili_test_uuid IS DISTINCT FROM OLD.son_basarili_test_uuid
                OR NEW.test_edilme_zamani IS DISTINCT FROM OLD.test_edilme_zamani
                OR NEW.aktiflestirilme_zamani IS NULL THEN
            RAISE EXCEPTION 'Activation may only add its activation timestamp.';
        END IF;
    ELSE
        IF NEW.aktiflestirilme_zamani IS DISTINCT FROM OLD.aktiflestirilme_zamani THEN
            RAISE EXCEPTION 'Activation timestamp may change only during activation.';
        END IF;
        SELECT *
          INTO v_test
          FROM entegrasyon.baglanti_surumu_testi
         WHERE proje_id = NEW.proje_id
           AND baglanti_id = NEW.baglanti_id
           AND baglanti_surumu_id = NEW.baglanti_surumu_id
           AND uuid = NEW.son_basarili_test_uuid;
        IF NOT FOUND
                OR v_test.sonuc_kodu <> 'PASSED'
                OR v_test.hedef_kimlik_surumu IS DISTINCT FROM NEW.hedef_kimlik_surumu
                OR v_test.hedef_parmak_izi IS DISTINCT FROM NEW.hedef_parmak_izi
                OR v_test.tamamlanma_zamani IS DISTINCT FROM NEW.test_edilme_zamani THEN
            RAISE EXCEPTION 'Lifecycle test evidence is invalid.';
        END IF;
    END IF;

    NEW.guncellenme_zamani := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_baglanti_surumu_yasam_dongusu_dogrula
BEFORE INSERT OR UPDATE OR DELETE ON baglanti_surumu_yasam_dongusu
FOR EACH ROW EXECUTE FUNCTION fn_baglanti_surumu_yasam_dongusu_dogrula();
