CREATE TABLE baglanti_surumu_yasam_dongusu (
    proje_id BIGINT NOT NULL,
    baglanti_id BIGINT NOT NULL,
    baglanti_surumu_id BIGINT NOT NULL,
    durum_kodu TEXT NOT NULL DEFAULT 'DRAFT',
    durum_surumu BIGINT NOT NULL DEFAULT 1,
    hedef_kimlik_surumu INTEGER,
    hedef_parmak_izi TEXT,
    son_basarili_test_uuid UUID,
    test_edilme_zamani TIMESTAMPTZ,
    aktiflestirilme_zamani TIMESTAMPTZ,
    guncellenme_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_baglanti_surumu_yasam_dongusu PRIMARY KEY (baglanti_surumu_id),
    CONSTRAINT uq_baglanti_surumu_yasam_dongusu_bag
        UNIQUE (proje_id, baglanti_id, baglanti_surumu_id),
    CONSTRAINT fk_baglanti_surumu_yasam_dongusu_proje
        FOREIGN KEY (proje_id) REFERENCES proje(id),
    CONSTRAINT fk_baglanti_surumu_yasam_dongusu_baglanti
        FOREIGN KEY (proje_id, baglanti_id) REFERENCES baglanti(proje_id, id),
    CONSTRAINT fk_baglanti_surumu_yasam_dongusu_surum
        FOREIGN KEY (proje_id, baglanti_surumu_id)
        REFERENCES baglanti_surumu(proje_id, id),
    CONSTRAINT ck_baglanti_surumu_yasam_dongusu_durum
        CHECK (durum_kodu IN ('DRAFT', 'TESTED', 'ACTIVE')),
    CONSTRAINT ck_baglanti_surumu_yasam_dongusu_surum_no
        CHECK (durum_surumu > 0),
    CONSTRAINT ck_baglanti_surumu_yasam_dongusu_hedef
        CHECK (
            (durum_kodu = 'DRAFT'
                AND hedef_kimlik_surumu IS NULL
                AND hedef_parmak_izi IS NULL
                AND son_basarili_test_uuid IS NULL
                AND test_edilme_zamani IS NULL
                AND aktiflestirilme_zamani IS NULL)
            OR
            (durum_kodu = 'TESTED'
                AND hedef_kimlik_surumu > 0
                AND hedef_parmak_izi ~ '^[0-9a-f]{64}$'
                AND son_basarili_test_uuid IS NOT NULL
                AND test_edilme_zamani IS NOT NULL
                AND aktiflestirilme_zamani IS NULL)
            OR
            (durum_kodu = 'ACTIVE'
                AND hedef_kimlik_surumu > 0
                AND hedef_parmak_izi ~ '^[0-9a-f]{64}$'
                AND son_basarili_test_uuid IS NOT NULL
                AND test_edilme_zamani IS NOT NULL
                AND aktiflestirilme_zamani IS NOT NULL)
        )
);

CREATE TABLE baglanti_surumu_testi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proje_id BIGINT NOT NULL,
    baglanti_id BIGINT NOT NULL,
    baglanti_surumu_id BIGINT NOT NULL,
    uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    deneme_no INTEGER NOT NULL,
    sonuc_kodu TEXT NOT NULL,
    hata_kodu TEXT,
    database_product TEXT,
    database_version TEXT,
    database_major INTEGER,
    database_minor INTEGER,
    driver_name TEXT,
    driver_version TEXT,
    hedef_kimlik_surumu INTEGER,
    hedef_parmak_izi TEXT,
    baslama_zamani TIMESTAMPTZ NOT NULL,
    tamamlanma_zamani TIMESTAMPTZ NOT NULL,
    sure_ms BIGINT NOT NULL,
    CONSTRAINT pk_baglanti_surumu_testi PRIMARY KEY (id),
    CONSTRAINT uq_baglanti_surumu_testi_uuid UNIQUE (uuid),
    CONSTRAINT uq_baglanti_surumu_testi_deneme
        UNIQUE (baglanti_surumu_id, deneme_no),
    CONSTRAINT uq_baglanti_surumu_testi_bag
        UNIQUE (proje_id, baglanti_id, baglanti_surumu_id, uuid),
    CONSTRAINT fk_baglanti_surumu_testi_proje
        FOREIGN KEY (proje_id) REFERENCES proje(id),
    CONSTRAINT fk_baglanti_surumu_testi_baglanti
        FOREIGN KEY (proje_id, baglanti_id) REFERENCES baglanti(proje_id, id),
    CONSTRAINT fk_baglanti_surumu_testi_yasam_dongusu
        FOREIGN KEY (proje_id, baglanti_id, baglanti_surumu_id)
        REFERENCES baglanti_surumu_yasam_dongusu(proje_id, baglanti_id, baglanti_surumu_id),
    CONSTRAINT ck_baglanti_surumu_testi_deneme_no CHECK (deneme_no > 0),
    CONSTRAINT ck_baglanti_surumu_testi_sonuc
        CHECK (sonuc_kodu IN ('PASSED', 'FAILED', 'TARGET_MISMATCH')),
    CONSTRAINT ck_baglanti_surumu_testi_sure
        CHECK (sure_ms >= 0 AND tamamlanma_zamani >= baslama_zamani),
    CONSTRAINT ck_baglanti_surumu_testi_parmak_izi
        CHECK (hedef_parmak_izi IS NULL OR hedef_parmak_izi ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_baglanti_surumu_testi_sonuc_yapisi
        CHECK (
            (sonuc_kodu = 'PASSED'
                AND hata_kodu IS NULL
                AND database_product IS NOT NULL
                AND database_version IS NOT NULL
                AND database_major >= 0
                AND database_minor >= 0
                AND driver_name IS NOT NULL
                AND driver_version IS NOT NULL
                AND hedef_kimlik_surumu > 0
                AND hedef_parmak_izi ~ '^[0-9a-f]{64}$')
            OR
            (sonuc_kodu = 'FAILED'
                AND hata_kodu IS NOT NULL)
            OR
            (sonuc_kodu = 'TARGET_MISMATCH'
                AND hata_kodu IS NOT NULL
                AND hedef_kimlik_surumu > 0
                AND hedef_parmak_izi ~ '^[0-9a-f]{64}$')
        )
);

ALTER TABLE baglanti_surumu_yasam_dongusu
