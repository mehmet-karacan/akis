CREATE TABLE prosedur_adim_durumu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proje_id BIGINT NOT NULL REFERENCES proje(id),
    calistirma_id BIGINT NOT NULL,
    calistirma_adimi_id BIGINT NOT NULL,
    prosedur_adim_kaniti_id BIGINT NOT NULL,
    durum_kodu TEXT NOT NULL DEFAULT 'BEKLIYOR',
    son_olay_no BIGINT,
    baslama_zamani TIMESTAMPTZ,
    bitis_zamani TIMESTAMPTZ,
    satir_sayisi BIGINT,
    bayt_sayisi BIGINT,
    hata_kodu TEXT,
    uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    olusturulma_zamani TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    olusturan_kullanici_id BIGINT REFERENCES kullanici(id),
    guncellenme_zamani TIMESTAMPTZ,
    guncelleyen_kullanici_id BIGINT REFERENCES kullanici(id),
    versiyon_no BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT pk_prosedur_adim_durumu PRIMARY KEY (id),
    CONSTRAINT uq_prosedur_adim_durumu_uuid UNIQUE (uuid),
    CONSTRAINT uq_prosedur_adim_durumu_adim UNIQUE (calistirma_adimi_id),
    CONSTRAINT uq_prosedur_adim_durumu_kanit UNIQUE (prosedur_adim_kaniti_id),
    CONSTRAINT uq_prosedur_adim_durumu_proje_id_id UNIQUE (proje_id, id),
    CONSTRAINT fk_prosedur_adim_durumu_run
        FOREIGN KEY (proje_id, calistirma_id)
        REFERENCES calistirma(proje_id, id),
    CONSTRAINT fk_prosedur_adim_durumu_adim
        FOREIGN KEY (proje_id, calistirma_adimi_id)
        REFERENCES calistirma_adimi(proje_id, id),
    CONSTRAINT fk_prosedur_adim_durumu_kanit
        FOREIGN KEY (proje_id, prosedur_adim_kaniti_id)
        REFERENCES prosedur_adim_kaniti(proje_id, id),
    CONSTRAINT ck_prosedur_adim_durumu_kod CHECK (durum_kodu IN (
        'BEKLIYOR', 'CALISIYOR', 'BASARILI', 'HATA_DEVAM',
        'BASARISIZ', 'SONUC_BELIRSIZ', 'ATLANDI')),
    CONSTRAINT ck_prosedur_adim_durumu_sayim CHECK (
        (satir_sayisi IS NULL OR satir_sayisi >= 0)
        AND (bayt_sayisi IS NULL OR bayt_sayisi >= 0)),
    CONSTRAINT ck_prosedur_adim_durumu_sekil CHECK (
        (durum_kodu = 'BEKLIYOR'
            AND son_olay_no IS NULL AND baslama_zamani IS NULL
            AND bitis_zamani IS NULL AND hata_kodu IS NULL)
        OR (durum_kodu = 'CALISIYOR'
            AND son_olay_no > 0 AND baslama_zamani IS NOT NULL
            AND bitis_zamani IS NULL AND hata_kodu IS NULL)
        OR (durum_kodu = 'BASARILI'
            AND son_olay_no > 0 AND baslama_zamani IS NOT NULL
            AND bitis_zamani IS NOT NULL AND hata_kodu IS NULL)
        OR (durum_kodu IN ('HATA_DEVAM', 'BASARISIZ')
            AND son_olay_no > 0 AND baslama_zamani IS NOT NULL
            AND bitis_zamani IS NOT NULL AND hata_kodu IS NOT NULL)
        OR (durum_kodu = 'SONUC_BELIRSIZ'
            AND son_olay_no > 0 AND baslama_zamani IS NOT NULL
            AND bitis_zamani IS NOT NULL)
        OR (durum_kodu = 'ATLANDI'
            AND son_olay_no > 0 AND baslama_zamani IS NULL
            AND bitis_zamani IS NOT NULL))
);

