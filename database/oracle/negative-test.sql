-- Batch evidence exists with its transaction and vanishes on rollback.
DECLARE
    C_T CONSTANT VARCHAR2(64):=RPAD('f',64,'f');
    C_J CONSTANT VARCHAR2(36):='11111111-1111-1111-1111-111111111111';
    C_R CONSTANT VARCHAR2(36):='22222222-2222-2222-2222-222222222222';
    C_REL CONSTANT VARCHAR2(64):=RPAD('a',64,'a');
    C_PLAN CONSTANT VARCHAR2(64):=RPAD('b',64,'b');
    C_PAY CONSTANT VARCHAR2(64):=RPAD('c',64,'c');
    C_KEY CONSTANT VARCHAR2(64):=RPAD('d',64,'d');
    V_G VARCHAR2(32); V_A NUMBER; V_M NUMBER; V_N NUMBER;
    V_R VARCHAR2(36); V_ATT NUMBER; V_TOK NUMBER; V_AT TIMESTAMP WITH TIME ZONE;
BEGIN
    ETL_KANIT_PKG.PREPARE_BATCH(
        C_T,C_J,'TRANSFER_1','FULL',C_KEY,0,C_R,1,101,
        C_REL,C_PLAN,C_PAY,10,1000,V_G,V_A);
    IF V_A<>0 OR V_G IS NULL THEN RAISE_APPLICATION_ERROR(-20903,'batch prepare failed'); END IF;
    BEGIN
        ETL_KANIT_PKG.RECORD_BATCH(
            NULL,C_T,C_J,'TRANSFER_1','FULL',C_KEY,0,C_R,1,101,
            C_REL,C_PLAN,C_PAY,10,1000);
        RAISE_APPLICATION_ERROR(-20916,'null batch guard accepted');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-20018 THEN RAISE; END IF; END;
    ETL_KANIT_PKG.RECORD_BATCH(
        V_G,C_T,C_J,'TRANSFER_1','FULL',C_KEY,0,C_R,1,101,
        C_REL,C_PLAN,C_PAY,10,1000);
    ETL_KANIT_PKG.VERIFY_BATCH(
        C_T,C_J,'TRANSFER_1','FULL',C_KEY,0,C_REL,C_PLAN,C_PAY,10,1000,
        V_M,V_R,V_ATT,V_TOK,V_AT);
    IF V_M<>1 OR V_R<>C_R OR V_ATT<>1 OR V_TOK<>101 OR V_AT IS NULL THEN
        RAISE_APPLICATION_ERROR(-20919,'batch evidence mismatch'); END IF;
    BEGIN
        ETL_KANIT_PKG.VERIFY_BATCH(
            C_T,C_J,'TRANSFER_1','FULL',C_KEY,0,C_REL,C_PLAN,RPAD('9',64,'9'),
            10,1000,V_M,V_R,V_ATT,V_TOK,V_AT);
        RAISE_APPLICATION_ERROR(-20921,'conflicting batch verify accepted');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-20015 THEN RAISE; END IF; END;
    BEGIN UPDATE ETL_YUKLEME_DEFTERI SET ROW_COUNT=11 WHERE TARGET_KEY_HASH=C_T;
        RAISE_APPLICATION_ERROR(-20908,'batch update accepted');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-20081 THEN RAISE; END IF; END;
    BEGIN DELETE FROM ETL_YUKLEME_DEFTERI WHERE TARGET_KEY_HASH=C_T;
        RAISE_APPLICATION_ERROR(-20909,'batch delete accepted');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-20081 THEN RAISE; END IF; END;
    SELECT COUNT(*) INTO V_N FROM ETL_YUKLEME_DEFTERI WHERE TARGET_KEY_HASH=C_T;
    IF V_N<>1 THEN RAISE_APPLICATION_ERROR(-20914,'batch marker count mismatch'); END IF;
END;
/
ROLLBACK;

-- Publish evidence follows the same clean-start, guard and rollback rules.
DECLARE
    C_T CONSTANT VARCHAR2(64):=RPAD('f',64,'f');
    C_J CONSTANT VARCHAR2(36):='11111111-1111-1111-1111-111111111111';
    C_R CONSTANT VARCHAR2(36):='22222222-2222-2222-2222-222222222222';
    C_REL CONSTANT VARCHAR2(64):=RPAD('a',64,'a');
    C_PLAN CONSTANT VARCHAR2(64):=RPAD('b',64,'b');
    C_STAGE CONSTANT VARCHAR2(64):=RPAD('0',64,'0');
    C_KEY CONSTANT VARCHAR2(64):=RPAD('e',64,'e');
    V_G VARCHAR2(32); V_A NUMBER; V_M NUMBER; V_N NUMBER;
    V_R VARCHAR2(36); V_ATT NUMBER; V_TOK NUMBER; V_AT TIMESTAMP WITH TIME ZONE;
BEGIN
    ETL_KANIT_PKG.PREPARE_PUBLISH(
        C_T,C_J,'PUBLISH_1',C_KEY,C_R,1,101,C_REL,C_PLAN,C_STAGE,
        10,10,0,'0001','0010',V_G,V_A);
    IF V_A<>0 OR V_G IS NULL THEN RAISE_APPLICATION_ERROR(-20910,'publish prepare failed'); END IF;
    BEGIN
        ETL_KANIT_PKG.RECORD_PUBLISH(
            NULL,C_T,C_J,'PUBLISH_1',C_KEY,C_R,1,101,C_REL,C_PLAN,C_STAGE,
            10,10,0,'0001','0010');
        RAISE_APPLICATION_ERROR(-20917,'null publish guard accepted');
