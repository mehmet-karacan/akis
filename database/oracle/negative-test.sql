        C_T,C_J,'PUBLISH_1',C_KEY,C_REL,C_PLAN,C_STAGE,10,10,0,'0001','0010',
        V_M,V_R,V_ATT,V_TOK,V_AT);
    IF V_M<>1 OR V_R<>C_R OR V_ATT<>1 OR V_TOK<>101 OR V_AT IS NULL THEN
        RAISE_APPLICATION_ERROR(-20922,'publish evidence mismatch'); END IF;
    BEGIN
        ETL_KANIT_PKG.VERIFY_PUBLISH(
            C_T,C_J,'PUBLISH_1',C_KEY,C_REL,C_PLAN,C_STAGE,10,9,0,'0001','0010',
            V_M,V_R,V_ATT,V_TOK,V_AT);
        RAISE_APPLICATION_ERROR(-20924,'conflicting publish verify accepted');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-20022 THEN RAISE; END IF; END;
    BEGIN UPDATE ETL_YAYIN_DEFTERI SET PUBLISHED_ROW_COUNT=11 WHERE TARGET_KEY_HASH=C_T;
        RAISE_APPLICATION_ERROR(-20912,'publish update accepted');
