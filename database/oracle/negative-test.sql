        RAISE_APPLICATION_ERROR(-20913,'publish delete accepted');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-20082 THEN RAISE; END IF; END;
    SELECT COUNT(*) INTO V_N FROM ETL_YAYIN_DEFTERI WHERE TARGET_KEY_HASH=C_T;
    IF V_N<>1 THEN RAISE_APPLICATION_ERROR(-20915,'publish marker count mismatch'); END IF;
END;
/
ROLLBACK;

