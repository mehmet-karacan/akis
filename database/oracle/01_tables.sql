            CONSTRAINT ETL_YD_PART_CK CHECK (
                REGEXP_LIKE(PARTITION_CODE, '^[A-Za-z0-9_.:-]+$', 'c')),
            CONSTRAINT ETL_YD_BKEY_CK CHECK (
