            CONSTRAINT ETL_YYD_RROWS_CK CHECK (REJECTED_ROW_COUNT >= 0),
            CONSTRAINT ETL_YYD_WM_CK CHECK (
                (LOWER_WATERMARK IS NULL AND UPPER_WATERMARK IS NULL) OR
                (LOWER_WATERMARK IS NOT NULL AND UPPER_WATERMARK IS NOT NULL))
        )~');
