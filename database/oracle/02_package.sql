    PROCEDURE PREPARE_PUBLISH(
        P_TARGET_KEY_HASH IN VARCHAR2,
        P_JOB_UUID IN VARCHAR2,
        P_STEP_CODE IN VARCHAR2,
        P_PUBLISH_KEY_HASH IN VARCHAR2,
        P_RUN_UUID IN VARCHAR2,
        P_ATTEMPT_NO IN NUMBER,
        P_FENCE_TOKEN IN NUMBER,
        P_RELEASE_HASH IN VARCHAR2,
        P_PLAN_HASH IN VARCHAR2,
        P_STAGE_HASH IN VARCHAR2,
        P_STAGE_ROW_COUNT IN NUMBER,
        P_PUBLISHED_ROW_COUNT IN NUMBER,
        P_REJECTED_ROW_COUNT IN NUMBER,
        P_LOWER_WATERMARK IN VARCHAR2,
        P_UPPER_WATERMARK IN VARCHAR2,
        O_TX_GUARD OUT VARCHAR2,
        O_ALREADY_RECORDED OUT NUMBER) IS
        V_RELEASE VARCHAR2(64);
        V_PLAN VARCHAR2(64);
        V_STAGE VARCHAR2(64);
        V_STAGE_ROWS NUMBER;
        V_PUBLISHED_ROWS NUMBER;
        V_REJECTED_ROWS NUMBER;
        V_LOWER VARCHAR2(1000);
        V_UPPER VARCHAR2(1000);
    BEGIN
        ASSERT_CLEAN_TRANSACTION;
        O_TX_GUARD := NULL;
        O_ALREADY_RECORDED := 0;
        CLEAR_STALE_GUARDS;
        IF G_PUBLISH_GUARD IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20021, 'a publish guard is already active in this transaction');
        END IF;
        ASSERT_PUBLISH_INPUTS(
            P_TARGET_KEY_HASH, P_JOB_UUID, P_STEP_CODE, P_PUBLISH_KEY_HASH,
            P_RUN_UUID, P_ATTEMPT_NO, P_FENCE_TOKEN, P_RELEASE_HASH,
            P_PLAN_HASH, P_STAGE_HASH, P_STAGE_ROW_COUNT,
            P_PUBLISHED_ROW_COUNT, P_REJECTED_ROW_COUNT,
            P_LOWER_WATERMARK, P_UPPER_WATERMARK);
        LOCK_AND_VERIFY_FENCE(
            P_TARGET_KEY_HASH, P_FENCE_TOKEN, P_JOB_UUID, P_RUN_UUID,
            P_ATTEMPT_NO, P_RELEASE_HASH, P_PLAN_HASH);

        BEGIN
            SELECT RELEASE_HASH, PLAN_HASH, STAGE_HASH, STAGE_ROW_COUNT,
                   PUBLISHED_ROW_COUNT, REJECTED_ROW_COUNT,
                   LOWER_WATERMARK, UPPER_WATERMARK
              INTO V_RELEASE, V_PLAN, V_STAGE, V_STAGE_ROWS,
                   V_PUBLISHED_ROWS, V_REJECTED_ROWS, V_LOWER, V_UPPER
              FROM ETL_YAYIN_DEFTERI
             WHERE TARGET_KEY_HASH = P_TARGET_KEY_HASH
               AND JOB_UUID = P_JOB_UUID
               AND STEP_CODE = P_STEP_CODE
               AND PUBLISH_KEY_HASH = P_PUBLISH_KEY_HASH;
            IF V_RELEASE <> P_RELEASE_HASH OR V_PLAN <> P_PLAN_HASH OR
               V_STAGE <> P_STAGE_HASH OR V_STAGE_ROWS <> P_STAGE_ROW_COUNT OR
               V_PUBLISHED_ROWS <> P_PUBLISHED_ROW_COUNT OR
               V_REJECTED_ROWS <> P_REJECTED_ROW_COUNT OR
               NOT SAME_TEXT(V_LOWER, P_LOWER_WATERMARK) OR
               NOT SAME_TEXT(V_UPPER, P_UPPER_WATERMARK) THEN
                RAISE_APPLICATION_ERROR(-20022, 'publish evidence conflicts with existing marker');
            END IF;
            O_ALREADY_RECORDED := 1;
            RETURN;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN NULL;
        END;

        G_PUBLISH_GUARD := LOWER(RAWTOHEX(SYS_GUID()));
        G_PUBLISH_TX_ID := DBMS_TRANSACTION.LOCAL_TRANSACTION_ID(TRUE);
        G_PUBLISH_SIGNATURE := PUBLISH_SIGNATURE(
            P_TARGET_KEY_HASH, P_JOB_UUID, P_STEP_CODE, P_PUBLISH_KEY_HASH,
            P_RUN_UUID, P_ATTEMPT_NO, P_FENCE_TOKEN, P_RELEASE_HASH,
            P_PLAN_HASH, P_STAGE_HASH, P_STAGE_ROW_COUNT,
            P_PUBLISHED_ROW_COUNT, P_REJECTED_ROW_COUNT,
            P_LOWER_WATERMARK, P_UPPER_WATERMARK);
        IF G_PUBLISH_TX_ID IS NULL THEN
            RAISE_APPLICATION_ERROR(-20023, 'publish preparation has no local transaction');
        END IF;
        O_TX_GUARD := G_PUBLISH_GUARD;
    END;

