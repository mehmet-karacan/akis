           AND BATCH_NO = P_BATCH_NO;
        IF V_BATCH_NO_COLLISION <> 0 THEN
            RAISE_APPLICATION_ERROR(-20016, 'batch number maps to a different batch key');
        END IF;

        G_BATCH_GUARD := LOWER(RAWTOHEX(SYS_GUID()));
        G_BATCH_TX_ID := DBMS_TRANSACTION.LOCAL_TRANSACTION_ID(TRUE);
