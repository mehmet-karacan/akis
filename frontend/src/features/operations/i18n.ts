export type OperationsMessageKey = keyof typeof en

export function useOperationsI18n() {
  const { i18n } = useTranslation()
  const language = i18n.resolvedLanguage === 'tr' || i18n.language.startsWith('tr') ? 'tr' : 'en'
  const messages = language === 'tr' ? tr : en
  const t = (key: OperationsMessageKey, values?: Record<string, string | number>) => {
    let message: string = messages[key] ?? en[key]
    if (values) {
      Object.entries(values).forEach(([name, value]) => {
        message = message.replaceAll(`{{${name}}}`, String(value))
      })
    }
    return message
  }
  return { language, locale: language === 'tr' ? 'tr-TR' : 'en-US', t }
}
