export type DefinitionsTranslationKey = keyof typeof en

function interpolate(value: string, values?: Record<string, string | number>) {
  if (!values) return value
  return Object.entries(values).reduce(
    (result, [key, replacement]) => result.replaceAll(`{{${key}}}`, String(replacement)),
    value,
  )
}

export function useDefinitionsI18n() {
  const { i18n } = useTranslation()
  const language = i18n.resolvedLanguage === 'tr' || i18n.language === 'tr' ? 'tr' : 'en'
  const dictionary = language === 'tr' ? tr : en
  const t = useCallback(
    (key: DefinitionsTranslationKey, values?: Record<string, string | number>) =>
      interpolate(dictionary[key], values),
    [dictionary],
  )

  return {
    language,
    t,
  }
}

