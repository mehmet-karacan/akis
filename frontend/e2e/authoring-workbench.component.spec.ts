// Exercise the browser HTML5 payload/handlers without Windows native drag UI.
// Physical mouse dragging remains a separate manual acceptance check.
async function dispatchColumnDrop(page: Page, source: Locator, target: Locator) {
  const dataTransfer = await page.evaluateHandle(() => new DataTransfer())
  try {
    await source.dispatchEvent('dragstart', { dataTransfer })
    await target.dispatchEvent('dragover', { dataTransfer })
    await target.dispatchEvent('drop', { dataTransfer })
    await source.dispatchEvent('dragend', { dataTransfer })
  } finally { await dataTransfer.dispose() }
}

