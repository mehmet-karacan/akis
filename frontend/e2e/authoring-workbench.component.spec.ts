for (const theme of ['light', 'dark']) test(`mouse-driven column drag maps without panning the canvas in ${theme}`, async ({ page }) => {
  test.setTimeout(25_000)
  await mockCatalog(page)
  await page.addInitScript(mode => localStorage.setItem('akis.theme', mode), theme)
  await page.setViewportSize({ width: 1366, height: 900 })
  await page.goto('/e2e/fixtures/authoring-workbench.html')
  const source = page.locator('.mapping-diagram-card--source .mapping-diagram-column[title="NAME · VARCHAR2(255)"]')
  const target = page.locator('.mapping-diagram-card--target .mapping-diagram-column[title="NAME · VARCHAR2(255)"]')
  await expect(source).toBeInViewport({ ratio: 1 })
  await expect(target).toBeInViewport({ ratio: 1 })
  await source.hover()
  const canvas = page.locator('.react-flow__viewport')
  const transform = await canvas.evaluate(element => getComputedStyle(element).transform)
  const moveTo = async (locator: Locator) => {
    const box = (await locator.boundingBox())!
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 6 })
  }
  // Incompatible targets must be visibly rejected, not silently mapped.
  const sourceId = page.locator('.mapping-diagram-card--source .mapping-diagram-column[title="ID · NUMBER(10,0)"]')
  await moveTo(sourceId)
  await page.mouse.down()
  await moveTo(target)
  await expect(target).toHaveClass(/is-incompatible-target/)
  await page.mouse.up()
  await expect(target.getByLabel('Not mapped', { exact: true })).toBeVisible()
  await expect(target).not.toHaveClass(/is-incompatible-target/)
  // Escape cancels even after a valid target has been highlighted.
  await moveTo(source)
  await page.mouse.down()
  await moveTo(target)
  await expect(target).toHaveClass(/is-drop-target/)
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(target.getByLabel('Not mapped', { exact: true })).toBeVisible()
  await expect(target).not.toHaveClass(/is-drop-target/)
  await source.dragTo(target, { timeout: 8000 })
  await expect(target.getByLabel('Mapped', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Column Properties', exact: true })).toHaveCount(0)
  expect(await canvas.evaluate(element => getComputedStyle(element).transform)).toBe(transform)
  expect(await page.evaluate(() => scrollY)).toBe(0)
  await target.click()
  await expect(page.getByRole('region', { name: 'Column Properties', exact: true }).locator('.cm-content')).toContainText('SRC_1.NAME')
})

