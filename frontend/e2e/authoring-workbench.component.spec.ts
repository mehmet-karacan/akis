// Real components/layout, synthetic metadata only. No source/target SQL or persisted edits.
async function mockCatalog(page: Page, newerSourceMetadata = false) {
  await page.route(/\/api\/v\d+\//, async route => {
    const path = new URL(route.request().url()).pathname
    if (path.endsWith('/mapping-expressions/compile')) {
      expect(route.request().method()).toBe('POST')
      const body = route.request().postDataJSON()
      expect(body.sources[0].alias).toBe('SRC_1')
      if (body.predicate === true && body.sql === 'SRC_1.ID > 10') {
        await route.fulfill({ json: { expression: { kind: 'BINARY', operator: '>', left: { kind: 'COLUMN', dataset: 'SOURCE_1', column: 'ID' }, right: { kind: 'LITERAL', value: 10 } }, references: [{ object: 'SOURCE_1', column: 'ID' }] } })
      } else if (body.sql === 'UPPER(SRC_1.NAME)') {
        await route.fulfill({ json: { expression: { kind: 'CALL', function: 'UPPER', args: [{ kind: 'COLUMN', dataset: 'SOURCE_1', column: 'NAME' }] }, references: [{ object: 'SOURCE_1', column: 'NAME' }] } })
      } else await route.fulfill({ status: 422, json: { code: 'MAPPING_EXPRESSION_INVALID', detail: 'Unsupported SQL function' } })
      return
    }
    expect(route.request().method()).toBe('GET')
    let json: unknown = []
    if (path.endsWith('/models')) json = [{ uuid: 'model', code: 'MODEL', name: 'Fixture Model', logicalSchemaUuid: 'logical', status: 'AKTIF', version: 1 }]
    if (path.endsWith('/submodels')) json = [{ uuid: 'folder', parentUuid: null, code: 'REPORTS', name: 'Reports', status: 'ACTIVE', version: 1 }]
    if (path.endsWith('/logical-schemas')) json = [{ uuid: 'logical', name: 'Fixture Schema', code: 'FIXTURE', status: 'AKTIF' }]
    if (path.endsWith('/data-objects')) json = [...['source', 'target'].map(role => ({ uuid: `${role}-object`, modelUuid: 'model', code: role.toUpperCase(), name: `${role} table`, objectReference: `APP.${role.toUpperCase()}`, type: 'TABLE', status: 'AKTIF', version: 1 })),
      { uuid: 'view-object', modelUuid: 'model', submodelUuid: 'folder', code: 'VIEW', name: 'Customer View', objectReference: 'APP.CUSTOMER_VIEW', type: 'VIEW', status: 'AKTIF', version: 1 }]
    if (path.endsWith('/schema-snapshots')) json = [{ uuid: 'snapshot', columns: [
      { reference: 'ID', producerType: 'NUMBER(10,0)', canonicalType: 'INTEGER', ordinal: 1, precision: 10, scale: 0, nullable: false },
      { reference: 'NAME', producerType: 'VARCHAR2(255)', canonicalType: 'STRING', ordinal: 2, length: 255, nullable: true },
    ], constraints: [] }]
    if (newerSourceMetadata && path.endsWith('/source-object/schema-snapshots')) json = [
      { uuid: 'new-snapshot', columns: [
        { reference: 'ID', producerType: 'NUMBER(10,0)', canonicalType: 'INTEGER', ordinal: 1, precision: 10, scale: 0, nullable: false },
        { reference: 'NEW_LABEL', producerType: 'VARCHAR2(500)', canonicalType: 'STRING', ordinal: 2, length: 500, nullable: true },
      ], constraints: [] }, ...(json as unknown[]),
    ]
    await route.fulfill({ json })
  })
}

